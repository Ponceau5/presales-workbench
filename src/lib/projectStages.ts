export function stagesForProject(projectId: string) {
  return projectId !== "RCJM1"
    ? stages
    : stages.map((d) => {
        const resources = projectResources.filter((r) =>
          (rackStageResources[d.id] || []).includes(r.id),
        );
        const source =
          resources.map((r) => r.title + " · " + r.version).join("；") ||
          "Racks Central 项目档案 · 2026-09-15";
        return {
          ...d,
          input: source,
          source,
          question: confirmations[d.id] || d.question,
          outputs: d.outputs.map((r, i) => ({
            ...r,
            text: content[d.id]?.[i] || "待责任人补齐资料并确认。",
            evidence: source,
          })),
          changedText: "请对照最新资料核对受影响内容，记录修改与复核依据。",
        };
      });
}
